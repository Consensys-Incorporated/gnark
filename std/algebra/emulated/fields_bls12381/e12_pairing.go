func (e Ext12) nSquare(z *E12, n int) *E12 {
	for i := 0; i < n; i++ {
		z = e.Square(z)
	}
	return z
}

func (e Ext12) nSquareGS(z *E12, n int) *E12 {
	for i := 0; i < n; i++ {
		z = e.CyclotomicSquareGS(z)
	}
	return z
}

// ExptNeg sets z to x^t in E12 and return z
// where t = -u = 15132376222941642752
func (e Ext12) ExptNeg(x *E12) *E12 {
	// Expt computation is derived from the addition chain:
	//
	//	_10      = 2*1
	//	_11      = 1 + _10
	//	_1100    = _11 << 2
	//	_1101    = 1 + _1100
	//	_1101000 = _1101 << 3
	//	_1101001 = 1 + _1101000
	//	return     ((_1101001 << 9 + 1) << 32 + 1) << 15
	//
	// Operations: 62 squares 5 multiplies
	//
	// Generated by github.com/mmcloughlin/addchain v0.4.0.

	z := e.Square(x)
	z = e.Mul(x, z)
	z = e.nSquare(z, 2)
	z = e.Mul(x, z)
	z = e.nSquare(z, 3)
	z = e.Mul(x, z)
	z = e.nSquare(z, 9)
	z = e.Mul(x, z)
	z = e.nSquare(z, 32)
	z = e.Mul(x, z)
	z = e.nSquare(z, 15)
	z = e.Square(z)

	return z
}

// ExptGS sets z to x^t in E12 and return z
// where t = u = -15132376222941642752
func (e Ext12) ExptGS(x *E12) *E12 {
	// ExptGS computation is derived from the addition chain:
	//
	//	_10      = 2*1
	//	_11      = 1 + _10
	//	_1100    = _11 << 2
	//	_1101    = 1 + _1100
	//	_1101000 = _1101 << 3
	//	_1101001 = 1 + _1101000
	//	return     ((_1101001 << 9 + 1) << 32 + 1) << 15
	//
	// Operations: 62 squares 5 multiplies
	//
	// Generated by github.com/mmcloughlin/addchain v0.4.0.
	z := e.ExptHalfGS(x)
	z = e.CyclotomicSquareGS(z)
	return z
}

func (e Ext12) ExptHalfGS(x *E12) *E12 {
	z := e.CyclotomicSquareGS(x)
	z = e.Mul(x, z)
	z = e.nSquareGS(z, 2)
	z = e.Mul(x, z)
	z = e.nSquareGS(z, 3)
	z = e.Mul(x, z)
	z = e.nSquareGS(z, 9)
	z = e.Mul(x, z)
	z = e.nSquareGS(z, 32)
	z = e.Mul(x, z)
	z = e.nSquareGS(z, 15)
	z = e.Conjugate(z)

	return z
}

// MulBy02368 multiplies a by an E12 sparse element b of the form
//
//	b.A0  =  c00 - c01
//	b.A1  =  0
//	b.A2  =  c10 - c11
//	b.A3  =  1
//	b.A4  =  0
//	b.A5  =  0
//	b.A6  =  c01
//	b.A7  =  0
//	b.A8  =  c11
//	b.A9  =  0
//	b.A10 =  0
//	b.A11 =  0
func (e *Ext12) MulBy02368(a *E12, c0, c1 *E2) *E12 {
	b0 := e.fp.Sub(&c0.A0, &c0.A1)
	b2 := e.fp.Sub(&c1.A0, &c1.A1)
	b6 := &c0.A1
	b8 := &c1.A1

	d := e.fp.MulPolyModTrinomial12(
		[12]*baseEl{&a.A0, &a.A1, &a.A2, &a.A3, &a.A4, &a.A5, &a.A6, &a.A7, &a.A8, &a.A9, &a.A10, &a.A11},
		[12]*baseEl{b0, nil, b2, e.fp.One(), nil, nil, b6, nil, b8, nil, nil, nil},
		2, -2,
	)

	return &E12{
		A0:  *d[0],
		A1:  *d[1],
		A2:  *d[2],
		A3:  *d[3],
		A4:  *d[4],
		A5:  *d[5],
		A6:  *d[6],
		A7:  *d[7],
		A8:  *d[8],
		A9:  *d[9],
		A10: *d[10],
		A11: *d[11],
	}
}

// Mul02368By02368ThenMul computes a · (l0 · l1) where l0 and l1 are sparse lines.
// First multiplies the two sparse lines together (sparse × sparse = semi-sparse),
// then multiplies the result by a.
// The product of two sparse lines has zeros at positions 1 and 7.
func (e *Ext12) Mul02368By02368ThenMul(a *E12, c0_0, c1_0, c0_1, c1_1 *E2) *E12 {
	// Extract line coefficients for l0
	// l0 = b0 + b2*w² + 1*w³ + b6*w⁶ + b8*w⁸
	b0 := e.fp.Sub(&c0_0.A0, &c0_0.A1)
	b2 := e.fp.Sub(&c1_0.A0, &c1_0.A1)
	// b3 = 1 (implicit)
	b6 := &c0_0.A1
	b8 := &c1_0.A1

	// Extract line coefficients for l1
	// l1 = d0 + d2*w² + 1*w³ + d6*w⁶ + d8*w⁸
	d0 := e.fp.Sub(&c0_1.A0, &c0_1.A1)
	d2 := e.fp.Sub(&c1_1.A0, &c1_1.A1)
	// d3 = 1 (implicit)
	d6 := &c0_1.A1
	d8 := &c1_1.A1

	// Compute L = l0 · l1 (sparse × sparse)
	// L has non-zero coefficients at positions 0,2,3,4,5,6,8,9,10,11
	// Positions 1 and 7 are ZERO
	one := e.fp.One()
	evals := e.fp.EvalSystem([]emulated.PolySpec[emulated.BLS12381Fp]{
		// L_0 = b0*d0 - 2*b6*d6
		{At: [][]*baseEl{{b0, d0}, {b6, d6}}, Coefs: []int{1, -2}},
		// L_2 = b0*d2 + b2*d0 - 2*(b6*d8 + b8*d6)
		{At: [][]*baseEl{{b0, d2}, {b2, d0}, {b6, d8}, {b8, d6}}, Coefs: []int{1, 1, -2, -2}},
		// L_4 = b2*d2 - 2*b8*d8
		{At: [][]*baseEl{{b2, d2}, {b8, d8}}, Coefs: []int{1, -2}},
		// L_6 = b0*d6 + b6*d0 + 2*b6*d6 + 1
		{At: [][]*baseEl{{b0, d6}, {b6, d0}, {b6, d6}, {one}}, Coefs: []int{1, 1, 2, 1}},
		// L_8 = b0*d8 + b2*d6 + b6*d2 + b8*d0 + 2*b6*d8 + 2*b8*d6
		{At: [][]*baseEl{{b0, d8}, {b2, d6}, {b6, d2}, {b8, d0}, {b6, d8}, {b8, d6}}, Coefs: []int{1, 1, 1, 1, 2, 2}},
		// L_10 = b2*d8 + b8*d2 + 2*b8*d8
		{At: [][]*baseEl{{b2, d8}, {b8, d2}, {b8, d8}}, Coefs: []int{1, 1, 2}},
	})

	L3 := e.fp.Add(b0, d0)
	L5 := e.fp.Add(b2, d2)
	L9 := e.fp.Add(b6, d6)
	L11 := e.fp.Add(b8, d8)

	// Now multiply a by L (semi-sparse multiplication)
	// L has zeros at positions 1 and 7
	return e.MulBySemiSparse1_7(a, evals[0], evals[1], L3, evals[2], L5, evals[3], evals[4], L9, evals[5], L11)
}

// MulBySemiSparse1_7 multiplies a by a semi-sparse E12 element b where b.A1 = b.A7 = 0.
// This is the result of multiplying two sparse lines together.
// b has non-zero coefficients: b0, b2, b3, b4, b5, b6, b8, b9, b10, b11
func (e *Ext12) MulBySemiSparse1_7(a *E12, b0, b2, b3, b4, b5, b6, b8, b9, b10, b11 *baseEl) *E12 {
	d := e.fp.MulPolyModTrinomial12(
		[12]*baseEl{&a.A0, &a.A1, &a.A2, &a.A3, &a.A4, &a.A5, &a.A6, &a.A7, &a.A8, &a.A9, &a.A10, &a.A11},
		[12]*baseEl{b0, nil, b2, b3, b4, b5, b6, nil, b8, b9, b10, b11},
		2, -2,
	)

	return &E12{
		A0:  *d[0],
		A1:  *d[1],
		A2:  *d[2],
		A3:  *d[3],
		A4:  *d[4],
		A5:  *d[5],
		A6:  *d[6],
		A7:  *d[7],
		A8:  *d[8],
		A9:  *d[9],
		A10: *d[10],
		A11: *d[11],
	}
}
